def load_or_create_manifest(maps_dir: Path) -> list[dict[str, Any]]:
    """Load or dynamically construct the test samples manifest ensuring 100% indexing integrity."""
    manifest_path = maps_dir / "test_samples_manifest.json"
    if manifest_path.exists():
        try:
            with open(manifest_path) as f:
                return json.load(f)
        except (OSError, json.JSONDecodeError):
            warn(
                "Could not parse %s. Deriving manifest dynamically from dataset.",
                manifest_path,
            )

    test_ds = CLIP_DATASET["test"]
    manifest = []
    for test_idx in range(len(test_ds)):
        global_idx = int(test_ds.indices[test_idx])
        row = test_ds.dataset.data.iloc[global_idx]
        img_raw = str(row.iloc[3])
        manifest.append(
            {
                "test_idx": test_idx,
                "global_csv_idx": global_idx,
                "image_path": img_raw,
                "image_name": Path(img_raw).name,
                "authenticity_score": float(row.iloc[1]),
            }
        )
    return manifest


def discover_heatmap_files(
    maps_dir: Path,
    methods: Sequence[str] = ("gradcam", "mpm"),
    models_filter: Sequence[str] | None = None,
    variants_filter: str = "best",
) -> dict[str, dict[str, dict[str, Path]]]:
    """Discover available .npy saliency map files grouped by method and model.

    Args:
        maps_dir: Root directory containing XAI_Maps (GradCAM and Multiscale_Pixel_Masking).
        methods: List of methods to discover ('gradcam', 'mpm').
        models_filter: Optional list of model names to include.
        variants_filter: Filter strategy: 'best', 'unpruned', 'greedy', 'negative', or 'all'.

    Returns:
        Nested mapping: {method: {model_name: {variant_tag: filepath}}}.
    """
    discovered: dict[str, dict[str, dict[str, Path]]] = defaultdict(
        lambda: defaultdict(dict)
    )
    model_order = get_model_order()
    known_models = sorted(model_order, key=len, reverse=True)

    method_dirs = {
        "gradcam": maps_dir / "GradCAM",
        "mpm": maps_dir / "Multiscale_Pixel_Masking",
    }

    for method in methods:
        dir_path = method_dirs.get(method)
        if not dir_path or not dir_path.exists():
            continue

        for file_path in sorted(dir_path.glob("*_maps.npy")):
            stem = file_path.stem.replace("_maps", "")
            matched_model: str | None = None
            variant_tag: str | None = None

            for km in known_models:
                if stem.startswith(f"{km}_"):
                    matched_model = km
                    variant_tag = stem[len(km) + 1 :]
                    break

            if not matched_model or not variant_tag:
                parts = stem.split("_", 1)
                if len(parts) >= 2:
                    matched_model, variant_tag = parts[0], parts[1]
                else:
                    continue

            if models_filter and matched_model not in models_filter:
                continue

            discovered[method][matched_model][variant_tag] = file_path

    # Apply variant filtering
    if variants_filter != "all":
        for method in list(discovered.keys()):
            for model_name in list(discovered[method].keys()):
                all_vars = discovered[method][model_name]
                if not all_vars:
                    continue

                if variants_filter == "best":
                    # Priority: unpruned exp1a variant 1 / best -> greedy -> negative -> first available
                    selected_var = _select_best_variant(list(all_vars.keys()))
                    discovered[method][model_name] = {
                        selected_var: all_vars[selected_var]
                    }
                else:
                    filtered = {
                        k: v
                        for k, v in all_vars.items()
                        if variants_filter in k.lower()
                    }
                    if filtered:
                        discovered[method][model_name] = filtered
                    else:
                        discovered[method][model_name] = {}

    return discovered


def _select_best_variant(variant_names: list[str]) -> str:
    """Select the primary / representative variant name from a list."""
    # 1. Base / unpruned variant 1
    for v in variant_names:
        if "exp1a_variant1" in v or "best" in v or "orig" in v:
            return v
    # 2. Any exp1a
    for v in variant_names:
        if "exp1a" in v:
            return v
    # 3. Greedy pruned
    for v in variant_names:
        if "greedy" in v:
            return v
    # 4. Fallback to first available
    return variant_names[0]


def select_sample_indices(
    dataset: Any,
    indices_arg: str | None = None,
    num_samples: int = 3,
    all_samples: bool = False,
) -> list[int]:
    """Select test dataset indices to render overlays for.

    Args:
        dataset: PyTorch dataset with (image, label/score) items.
        indices_arg: Optional comma-separated string of explicit indices.
        num_samples: Number of quantile-spaced sample images if indices_arg is None.
        all_samples: Whether to select all indices in the dataset.

    Returns:
        List of integer dataset indices.
    """
    total_len = len(dataset)
    if all_samples:
        return list(range(total_len))

    if indices_arg:
        indices = [int(idx.strip()) for idx in indices_arg.split(",") if idx.strip()]
        return [idx for idx in indices if 0 <= idx < total_len]

    # Authenticity quantile selection
    scores: list[float] = []
    for idx in range(total_len):
        _, target = dataset[idx]
        val = target.item() if isinstance(target, torch.Tensor) else float(target)
        scores.append(val)

    scores_arr = np.array(scores)
    quantiles = (
        [0.25, 0.50, 0.75]
        if num_samples == 3
        else np.linspace(0.1, 0.9, num_samples).tolist()
    )
    quantile_values = np.quantile(scores_arr, quantiles)

    chosen_indices: list[int] = []
    used = set()
    for qval in quantile_values:
        diffs = np.abs(scores_arr - qval)
        order = np.argsort(diffs)
        for candidate in order:
            c_int = int(candidate)
            if c_int not in used:
                used.add(c_int)
                chosen_indices.append(c_int)
                break

    return chosen_indices


def get_image_tensor_and_score(
    sample_idx: int, model_name: str
) -> tuple[torch.Tensor, float]:
    """Retrieve test image tensor and authenticity score appropriate for the model."""
    if "clip" in model_name.lower():
        ds = CLIP_DATASET["test"]
    elif "densenet" in model_name.lower():
        ds = DENSENET_DATASET["test"]
    else:
        ds = IMAGENET_DATASET["test"]

    img_tensor, target = ds[sample_idx]
    score = float(target.item() if isinstance(target, torch.Tensor) else target)
    return img_tensor, score


def generate_comparison_grid(
    sample_idx: int,
    orig_rgb: np.ndarray,
    auth_score: float,
    models_data: list[dict[str, Any]],
    output_path: Path,
    cmap_name: str = "bwr",
    alpha: float = 0.5,
    annotate: bool = False,
    dpi: int = 300,
) -> None:
    """Generate and save comparison figure for a single test sample.

    If annotate is False, generates a clean, borderless stitched horizontal strip
    of pure images with zero text or borders.
    If annotate is True, generates a labeled matplotlib figure with titles and scores.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    orig_uint8 = np.clip(orig_rgb * 255.0, 0, 255).astype(np.uint8)

    overlays = [
        render_overlay_rgb(
            orig_rgb, m_info["saliency"], cmap_name=cmap_name, alpha=alpha
        )
        for m_info in models_data
    ]

    if not annotate:
        # Pure borderless, annotation-free horizontal image strip
        all_panels = [orig_uint8] + overlays
        stitched = np.concatenate(all_panels, axis=1)
        cv2.imwrite(str(output_path), cv2.cvtColor(stitched, cv2.COLOR_RGB2BGR))
        return

    # Labeled matplotlib figure (if explicitly requested)
    n_panels = 1 + len(models_data)
    fig, axes = plt.subplots(1, n_panels, figsize=(3.2 * n_panels, 3.8), dpi=dpi)
    if n_panels == 1:
        axes = [axes]

    axes[0].imshow(orig_uint8)
    axes[0].set_title(
        f"Original\n(Auth: {auth_score:.3f})", fontsize=11, fontweight="bold"
    )
    axes[0].axis("off")

    for ax_idx, (m_info, overlay_rgb) in enumerate(
        zip(models_data, overlays, strict=False), start=1
    ):
        axes[ax_idx].imshow(overlay_rgb)
        label = f"{m_info['model_name']}\n[{m_info['method'].upper()}]"
        axes[ax_idx].set_title(label, fontsize=10)
        axes[ax_idx].axis("off")

    plt.tight_layout()
    fig.savefig(output_path, bbox_inches="tight", dpi=dpi)
    plt.close(fig)


def save_individual_overlays(
    sample_idx: int,
    orig_rgb: np.ndarray,
    models_data: list[dict[str, Any]],
    sample_dir: Path,
    cmap_name: str = "bwr",
    alpha: float = 0.5,
) -> None:
    """Save individual original, heatmap, and overlay images in a dedicated folder."""
    sample_dir.mkdir(parents=True, exist_ok=True)

    # 1. Save original image
    orig_uint8 = (orig_rgb * 255).astype(np.uint8)
    cv2.imwrite(
        str(sample_dir / "original.png"), cv2.cvtColor(orig_uint8, cv2.COLOR_RGB2BGR)
    )

    # 2. Save individual heatmaps and overlays
    try:
        cmap = plt.get_cmap(cmap_name)
    except (ValueError, KeyError):
        cmap = plt.get_cmap("coolwarm")

    for m_info in models_data:
        m_name = m_info["model_name"]
        meth = m_info["method"]
        var = m_info["variant"]
        saliency = m_info["saliency"]

        # Overlay
        overlay_rgb = render_overlay_rgb(
            orig_rgb, saliency, cmap_name=cmap_name, alpha=alpha
        )
        overlay_path = sample_dir / f"{m_name}_{var}_{meth}_overlay.png"
        cv2.imwrite(str(overlay_path), cv2.cvtColor(overlay_rgb, cv2.COLOR_RGB2BGR))

        # Raw Heatmap
        h, w = orig_rgb.shape[:2]
        s_resized = (
            cv2.resize(
                saliency.astype(np.float32), (w, h), interpolation=cv2.INTER_LINEAR
            )
            if saliency.shape[:2] != (h, w)
            else saliency.astype(np.float32)
        )
        s_min, s_max = float(s_resized.min()), float(s_resized.max())
        denom = s_max - s_min
        norm_s = (
            (s_resized - s_min) / denom
            if denom > 1e-8
            else np.full_like(s_resized, 0.5)
        )
        heat_rgb = (cmap(norm_s)[:, :, :3] * 255).astype(np.uint8)
        heat_path = sample_dir / f"{m_name}_{var}_{meth}_heatmap.png"
        cv2.imwrite(str(heat_path), cv2.cvtColor(heat_rgb, cv2.COLOR_RGB2BGR))


def run_visualization(
    maps_dir: Path,
    output_dir: Path,
    methods: Sequence[str] = ("gradcam", "mpm"),
    models_filter: Sequence[str] | None = None,
    variants_filter: str = "best",
    indices_arg: str | None = None,
    num_samples: int = 3,
    all_samples: bool = False,
    cmap_name: str = "bwr",
    alpha: float = 0.5,
    annotate: bool = False,
    dpi: int = 300,
) -> None:
    """Execute the full saliency overlay visualization pipeline."""
    info("Discovering precomputed saliency map arrays in %s...", maps_dir)
    discovered = discover_heatmap_files(
        maps_dir=maps_dir,
        methods=methods,
        models_filter=models_filter,
        variants_filter=variants_filter,
    )

    if not discovered:
        warn("No .npy heatmap files found in %s matching filters.", maps_dir)
        return

    # Check available models
    active_models = set()
    for meth in discovered:
        for m in discovered[meth]:
            active_models.add(m)

    if not active_models:
        warn("No models matched the specified criteria.")
        return

    ordered_models = [m for m in get_model_order() if m in active_models]
    info("Found %d models for visualization: %s", len(ordered_models), ordered_models)

    # Determine reference dataset for sample selection
    ref_dataset = CLIP_DATASET["test"]
    sample_indices = select_sample_indices(
        dataset=ref_dataset,
        indices_arg=indices_arg,
        num_samples=num_samples,
        all_samples=all_samples,
    )
    info("Selected %d test sample indices: %s", len(sample_indices), sample_indices)

    # Pre-load required maps into memory: {method: {model: {var: np.ndarray}}}
    loaded_arrays: dict[str, dict[str, dict[str, np.ndarray]]] = defaultdict(
        lambda: defaultdict(dict)
    )
    for meth in discovered:
        for m in discovered[meth]:
            for var, p in discovered[meth][m].items():
                try:
                    loaded_arrays[meth][m][var] = np.load(p)
                    info(
                        "Loaded [%s] %s (%s): shape %s",
                        meth,
                        m,
                        var,
                        loaded_arrays[meth][m][var].shape,
                    )
                except (OSError, ValueError) as e:
                    error("Failed to load map file %s: %s", p, e)

    output_dir.mkdir(parents=True, exist_ok=True)
    grids_dir = output_dir / "Comparison_Grids"
    individual_dir = output_dir / "Individual_Overlays"

    manifest = load_or_create_manifest(maps_dir)

    for sample_idx in sample_indices:
        meta_item = manifest[sample_idx] if sample_idx < len(manifest) else {}
        img_name = meta_item.get("image_name", f"{sample_idx:04d}.png")
        img_stem = Path(img_name).stem

        # Retrieve original image from dataset
        img_tensor, auth_score = get_image_tensor_and_score(sample_idx, "clip_vit_b16")
        auth_score = meta_item.get("authenticity_score", auth_score)
        denorm = denormalize_image(img_tensor)
        orig_rgb = denorm.permute(1, 2, 0).cpu().numpy()

        # Collect models' saliency maps for this sample
        sample_models_data: list[dict[str, Any]] = []
        for m_name in ordered_models:
            for meth in methods:
                if meth not in loaded_arrays or m_name not in loaded_arrays[meth]:
                    continue
                for var, maps_arr in loaded_arrays[meth][m_name].items():
                    if sample_idx < len(maps_arr):
                        sample_models_data.append(
                            {
                                "model_name": m_name,
                                "method": meth,
                                "variant": var,
                                "saliency": maps_arr[sample_idx],
                            }
                        )

        if not sample_models_data:
            warn(
                "No valid saliency maps found for sample index %d. Skipping.",
                sample_idx,
            )
            continue

        # 1. Comparison Strip / Grid (clean borderless by default)
        prefix = "grid_labeled" if annotate else "strip_clean"
        grid_file = grids_dir / f"{prefix}_sample_{sample_idx:04d}_{img_stem}.png"
        generate_comparison_grid(
            sample_idx=sample_idx,
            orig_rgb=orig_rgb,
            auth_score=auth_score,
            models_data=sample_models_data,
            output_path=grid_file,
            cmap_name=cmap_name,
            alpha=alpha,
            annotate=annotate,
            dpi=dpi,
        )
        info("Saved comparison figure: %s", grid_file)

        # 2. Individual Overlays (plain images, no annotations or borders)
        sample_folder = individual_dir / f"sample_{sample_idx:04d}_{img_stem}"
        save_individual_overlays(
            sample_idx=sample_idx,
            orig_rgb=orig_rgb,
            models_data=sample_models_data,
            sample_dir=sample_folder,
            cmap_name=cmap_name,
            alpha=alpha,
        )
        info("Saved individual overlays in: %s", sample_folder)

    info(
        "Overlay visualization completed successfully! Outputs written to: %s",
        output_dir,
    )


def main() -> None:
    """CLI entrypoint for saliency overlay visualization."""
    parser = argparse.ArgumentParser(
        description="Generate saliency overlays and comparison grids from precomputed .npy heatmaps."
    )
    parser.add_argument(
        "--maps-dir",
        type=Path,
        default=Path("Outputs/Experiment_2_variants/XAI_Maps"),
        help="Path to directory containing XAI_Maps.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("Outputs/Experiment_2_variants/Plots/Saliency_Overlays"),
        help="Directory to save generated overlay plots and images.",
    )
    parser.add_argument(
        "--models",
        type=str,
        default="all",
        help="Comma-separated model names to visualize, or 'all'.",
    )
    parser.add_argument(
        "--variants",
        type=str,
        default="best",
        choices=["best", "unpruned", "greedy", "negative", "all"],
        help="Variant selection strategy (default: 'best').",
    )
    parser.add_argument(
        "--methods",
        type=str,
        default="both",
        choices=["both", "gradcam", "mpm"],
        help="XAI methods to visualize (default: 'both').",
    )
    parser.add_argument(
        "--num-samples",
        type=int,
        default=3,
        help="Number of quantile-spaced test samples to render (default: 3).",
    )
    parser.add_argument(
        "--indices",
        type=str,
        default=None,
        help="Explicit comma-separated test image indices (e.g. '0,5,10').",
    )
    parser.add_argument(
        "--all",
        action="store_true",
        help="Render overlays for all test images in the dataset.",
    )
    parser.add_argument(
        "--cmap",
        type=str,
        default="bwr",
        help="Colormap for saliency maps (default: 'bwr').",
    )
    parser.add_argument(
        "--alpha",
        type=float,
        default=0.5,
        help="Overlay blending opacity (default: 0.5).",
    )
    parser.add_argument(
        "--annotate",
        action="store_true",
        help="Add text labels, titles, and score annotations to the comparison grid (default: False, produces clean borderless image strips).",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=300,
        help="DPI resolution for comparison grid figures (default: 300).",
    )

    args = parser.parse_args()

    models_list = (
        None
        if args.models.lower() == "all"
        else [m.strip() for m in args.models.split(",")]
    )
    methods_list = ["gradcam", "mpm"] if args.methods == "both" else [args.methods]

    run_visualization(
        maps_dir=args.maps_dir,
        output_dir=args.output_dir,
        methods=methods_list,
        models_filter=models_list,
        variants_filter=args.variants,
        indices_arg=args.indices,
        num_samples=args.num_samples,
        all_samples=args.all,
        cmap_name=args.cmap,
        alpha=args.alpha,
        annotate=args.annotate,
        dpi=args.dpi,
    )


if __name__ == "__main__":
    main()
